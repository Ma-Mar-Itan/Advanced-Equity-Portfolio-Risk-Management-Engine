function addBox(slide, left, top, width, height, fill, lineFill = fill, lineWidth = 0) {
  return slide.shapes.add({
    geometry: "rect",
    position: { left, top, width, height },
    fill,
    line: { style: "solid", fill: lineFill, width: lineWidth },
  });
}

function addText(slide, text, left, top, width, height, options = {}) {
  const shape = slide.shapes.add({
    geometry: "textbox",
    position: { left, top, width, height },
    fill: "none",
    line: { style: "solid", fill: "none", width: 0 },
  });
  shape.text = text;
  shape.text.style = {
    fontFamily: FONT,
    fontSize: options.fontSize ?? 18,
    bold: options.bold ?? false,
    color: options.color ?? BLACK,
    alignment: options.alignment ?? "left",
  };
  return shape;
}

function money(value, digits = 0) {
  const abs = Math.abs(value);
  if (abs >= 1_000_000) return `${value < 0 ? "−" : ""}$${(abs / 1_000_000).toFixed(digits || 2)}M`;
  return `${value < 0 ? "−" : ""}$${(abs / 1000).toFixed(digits)}K`;
}

function pct(value, digits = 1) {
  return `${(value * 100).toFixed(digits)}%`;
}

function addMetric(slide, value, label, top, color = BLACK) {
  addText(slide, value, 888, top, 300, 50, { fontSize: 34, bold: true, color });
  addText(slide, label, 888, top + 50, 300, 44, { fontSize: 15, color: MID });
}

